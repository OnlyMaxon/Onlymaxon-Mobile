/*
 * One screen for both signing in and registering, because from where the client is
 * standing those are the same act: they were handed a card, and now they are proving the
 * address written on it is theirs. Asking them to first work out which of two buttons
 * applies is a question only the database cares about.
 */

import {useCallback, useState} from 'react';
import {ActivityIndicator, Linking, Pressable, Text, TextInput, View} from 'react-native';

import {authErrorKey, register, resetPassword, signIn} from '../account';
import type {Key} from '../i18n';
import {C, s} from '../theme';

type T = (k: Key, v?: Record<string, string | number>) => string;

type Mode = 'in' | 'up';

/* Generated by build/apps.js in the site repository, from build/src/apps/cards/. */
const LEGAL = 'https://onlymaxon.com/apps/cards';

export function SignIn({t}: {t: T}) {
  const [mode, setMode] = useState<Mode>('in');
  const [email, setEmail] = useState('');
  const [password, setPassword] = useState('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [note, setNote] = useState<string | null>(null);
  const [asking, setAsking] = useState(false);

  const ready = /^[^@\s]+@[^@\s.]+\.[^@\s]+$/.test(email.trim()) && password.length >= 6;

  const submit = useCallback(async () => {
    setBusy(true);
    setError(null);
    setNote(null);
    try {
      // No navigation on success: the auth listener in App notices and swaps the screen.
      setAsking(false);
      if (mode === 'up') {
        await register(email, password);
      } else {
        await signIn(email, password);
      }
    } catch (e) {
      setError(t(authErrorKey(e)));
    } finally {
      setBusy(false);
    }
  }, [mode, email, password, t]);

  /*
   * Asking first, because this used to fire on one tap and did.
   *
   * The link sat directly under the sign-in button — its margin was on the text inside the
   * Pressable rather than on the Pressable, so the touch target began at the button's lower
   * edge, and a hitSlop of 10 pushed it up inside the button. A slightly low press on
   * "Sign in" sent a password reset email instead, silently, to somebody who had just
   * typed the correct password. The spacing below is fixed too; this is the other half.
   */
  const forgot = useCallback(async () => {
    setError(null);
    setNote(null);
    if (!asking) {
      setAsking(true);
      return;
    }
    setAsking(false);
    try {
      await resetPassword(email);
      // Said the same way whether or not the address exists — otherwise this form answers
      // the question "is this person a client of yours" for anybody who asks it.
      setNote(t('resetSent'));
    } catch (e) {
      setError(t(authErrorKey(e)));
    }
  }, [asking, email, t]);

  return (
    <View>
      <View style={s.tabs}>
        {(['in', 'up'] as const).map(m => (
          <Pressable
            key={m}
            style={[s.tab, mode === m ? s.tabActive : null]}
            onPress={() => {
              setMode(m);
              setError(null);
              setNote(null);
            }}>
            <Text style={[s.tabText, mode === m ? s.tabTextActive : null]}>
              {t(m === 'in' ? 'signIn' : 'signUp')}
            </Text>
          </Pressable>
        ))}
      </View>

      <Text style={s.label}>{t('email')}</Text>
      <TextInput
        style={s.input}
        value={email}
        onChangeText={setEmail}
        placeholder="anna@salon.pl"
        placeholderTextColor={C.dim}
        autoCapitalize="none"
        autoCorrect={false}
        keyboardType="email-address"
        textContentType="emailAddress"
      />

      <Text style={s.label}>{t('password')}</Text>
      <TextInput
        style={s.input}
        value={password}
        onChangeText={setPassword}
        placeholder={t('passwordHint')}
        placeholderTextColor={C.dim}
        secureTextEntry
        autoCapitalize="none"
        autoCorrect={false}
        textContentType={mode === 'up' ? 'newPassword' : 'password'}
      />

      {busy ? (
        <ActivityIndicator color={C.accent} style={s.spin} />
      ) : (
        <Pressable
          style={[s.primary, s.spacedSmall, !ready ? s.disabled : null]}
          disabled={!ready}
          onPress={submit}>
          <Text style={s.primaryText}>{t(mode === 'up' ? 'createAccount' : 'doSignIn')}</Text>
        </Pressable>
      )}

      {mode === 'in' ? (
        /* The margin lives on the Pressable, not on the Text inside it, so the touch
           target starts below the gap instead of at the button's edge. No hitSlop here
           for the same reason: this is the one control on the screen that must never be
           hit by accident. */
        <Pressable style={s.linkRow} onPress={forgot}>
          <Text style={[s.link, {textAlign: 'center'}]}>
            {asking ? t('forgotConfirm', {email: email.trim()}) : t('forgot')}
          </Text>
        </Pressable>
      ) : (
        <Text style={s.hint}>{t('signUpNote')}</Text>
      )}

      {error ? <Text style={s.error}>{error}</Text> : null}
      {note ? <Text style={s.done}>{note}</Text> : null}

      {/* The two documents, reachable before the account exists rather than only after.
          Apple asks for the privacy policy URL in App Store Connect, which is a different
          thing from a person being able to read it at the moment they are handing over an
          address. */}
      <View style={s.legalRow}>
        <Pressable onPress={() => Linking.openURL(`${LEGAL}/privacy/`)} hitSlop={8}>
          <Text style={s.legalLink}>{t('legalPrivacy')}</Text>
        </Pressable>
        <Pressable onPress={() => Linking.openURL(`${LEGAL}/terms/`)} hitSlop={8}>
          <Text style={s.legalLink}>{t('legalTerms')}</Text>
        </Pressable>
      </View>
    </View>
  );
}
