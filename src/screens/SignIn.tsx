/*
 * The first screen, which is the card and not a form.
 *
 * It used to open on two tabs and two fields, which is the shape of the database rather
 * than the shape of the moment: somebody is standing there holding a piece of black
 * plastic. So the plastic is what they see first, with nothing printed on it — that is what
 * people who have held one say they like about it — and underneath, one sentence about what
 * is about to happen and two buttons.
 *
 * Registering asks for everything the card needs in one go: a name, and what the card
 * should be called. That second answer is the address the chip will carry, so it is asked
 * for in the client's words and never as "slug". It is written down before the account is
 * created, because the next thing that happens is the person leaving for their mail to
 * confirm the address — see src/pending.ts.
 */

import {useCallback, useState} from 'react';
import {ActivityIndicator, Linking, Pressable, Text, TextInput, View} from 'react-native';

import {authErrorKey, register, resetPassword, signIn} from '../account';
import {BASE_URL, SLUG_RE} from '../cards';
import type {Key} from '../i18n';
import {savePending} from '../pending';
import {C, s} from '../theme';
import {MagicCard} from './MagicCard';

type T = (k: Key, v?: Record<string, string | number>) => string;

/* Nothing chosen yet, signing in, or registering. The first is not a hidden third state:
 * it is the screen almost everybody sees, and the only one with the card alone on it. */
type Mode = null | 'in' | 'up';

/* Generated by build/apps.js in the site repository, from build/src/apps/cards/. */
const LEGAL = 'https://onlymaxon.com/apps/cards';

/* "cards.onlymaxon.com/" — the address as a person reads it, without the scheme. */
const HOST = BASE_URL.replace(/^https?:\/\//, '');

export function SignIn({t}: {t: T}) {
  const [mode, setMode] = useState<Mode>(null);
  const [email, setEmail] = useState('');
  const [password, setPassword] = useState('');
  const [first, setFirst] = useState('');
  const [last, setLast] = useState('');
  const [slug, setSlug] = useState('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [note, setNote] = useState<string | null>(null);
  const [asking, setAsking] = useState(false);

  const clean = slug.trim().toLowerCase();
  const credentials = /^[^@\s]+@[^@\s.]+\.[^@\s]+$/.test(email.trim()) && password.length >= 6;

  /*
   * A surname is asked for and not insisted on. People without one exist, and a form that
   * refuses to let them register is a worse failure than a card whose name is one word —
   * which its owner can change in the editor anyway.
   */
  const ready =
    mode === 'up' ? credentials && !!first.trim() && SLUG_RE.test(clean) : credentials;

  const reset = (m: Mode) => {
    setMode(m);
    setError(null);
    setNote(null);
    setAsking(false);
  };

  const submit = useCallback(async () => {
    setBusy(true);
    setError(null);
    setNote(null);
    try {
      // No navigation on success: the auth listener in App notices and swaps the screen.
      setAsking(false);
      if (mode === 'up') {
        if (!SLUG_RE.test(clean)) {
          setError(t('cardNameBad'));
          return;
        }
        /*
         * Written down before the account exists, not after. Registering signs the person
         * in, which swaps this screen out from under us on the next render — and what they
         * typed has to survive that, and the trip to their mail after it.
         */
        await savePending({
          name: [first.trim(), last.trim()].filter(Boolean).join(' '),
          slug: clean,
        });
        await register(email, password);
      } else {
        await signIn(email, password);
      }
    } catch (e) {
      setError(t(authErrorKey(e)));
    } finally {
      setBusy(false);
    }
  }, [mode, email, password, first, last, clean, t]);

  /*
   * Asking first, because this used to fire on one tap and did.
   *
   * The link sat directly under the sign-in button — its margin was on the text inside the
   * Pressable rather than on the Pressable, so the touch target began at the button's lower
   * edge, and a hitSlop of 10 pushed it up inside the button. A slightly low press on
   * "Sign in" sent a password reset email instead, silently, to somebody who had just
   * typed the correct password. The spacing below is fixed too; this is the other half.
   */
  const forgot = useCallback(async () => {
    setError(null);
    setNote(null);
    if (!asking) {
      setAsking(true);
      return;
    }
    setAsking(false);
    try {
      await resetPassword(email);
      // Said the same way whether or not the address exists — otherwise this form answers
      // the question "is this person a client of yours" for anybody who asks it.
      setNote(t('resetSent'));
    } catch (e) {
      setError(t(authErrorKey(e)));
    }
  }, [asking, email, t]);

  return (
    <View>
      {/* The card with nothing on it. Not a placeholder for a missing one — the object as
          it arrives in the envelope, which is the thing being offered. */}
      <MagicCard card={null} t={t} />

      <Text style={[s.blockLabel, s.spaced]}>{t('activateTitle')}</Text>
      <Text style={s.blockText}>{t('activateWhy')}</Text>

      {mode === null ? (
        <View>
          <Pressable style={[s.primary, s.spaced]} onPress={() => reset('up')}>
            <Text style={s.primaryText}>{t('signUp')}</Text>
          </Pressable>
          <Pressable style={[s.secondary, s.spacedSmall]} onPress={() => reset('in')}>
            <Text style={s.secondaryText}>{t('signIn')}</Text>
          </Pressable>
        </View>
      ) : (
        <View style={s.spaced}>
          {mode === 'up' ? (
            <View>
              <Text style={s.label}>{t('firstName')}</Text>
              <TextInput
                style={s.input}
                value={first}
                onChangeText={setFirst}
                placeholder="Anna"
                placeholderTextColor={C.dim}
                autoCorrect={false}
                textContentType="givenName"
              />

              <Text style={s.label}>{t('lastName')}</Text>
              <TextInput
                style={s.input}
                value={last}
                onChangeText={setLast}
                placeholder="Kowalska"
                placeholderTextColor={C.dim}
                autoCorrect={false}
                textContentType="familyName"
              />
            </View>
          ) : null}

          <Text style={s.label}>{t('email')}</Text>
          <TextInput
            style={s.input}
            value={email}
            onChangeText={setEmail}
            placeholder="anna@salon.pl"
            placeholderTextColor={C.dim}
            autoCapitalize="none"
            autoCorrect={false}
            keyboardType="email-address"
            textContentType="emailAddress"
          />

          <Text style={s.label}>{t('password')}</Text>
          <TextInput
            style={s.input}
            value={password}
            onChangeText={setPassword}
            placeholder={t('passwordHint')}
            placeholderTextColor={C.dim}
            secureTextEntry
            autoCapitalize="none"
            autoCorrect={false}
            textContentType={mode === 'up' ? 'newPassword' : 'password'}
          />

          {mode === 'up' ? (
            <View>
              <Text style={s.label}>{t('cardName')}</Text>
              <TextInput
                style={s.input}
                value={slug}
                onChangeText={v => setSlug(v.replace(/\s+/g, '-').toLowerCase())}
                placeholder="anna-kowalska"
                placeholderTextColor={C.dim}
                autoCapitalize="none"
                autoCorrect={false}
              />
              {/* The address itself, spelled out as it will read on the chip. Somebody
                  deciding what to call their card is deciding what to print, and seeing it
                  is the difference between filling a field and making a decision. */}
              <Text style={s.hint}>{clean ? `${HOST}${clean}` : t('cardNameHint')}</Text>
            </View>
          ) : null}

          {busy ? (
            <ActivityIndicator color={C.accent} style={s.spin} />
          ) : (
            <Pressable
              style={[s.primary, s.spaced, !ready ? s.disabled : null]}
              disabled={!ready}
              onPress={submit}>
              <Text style={s.primaryText}>
                {t(mode === 'up' ? 'createAccount' : 'doSignIn')}
              </Text>
            </Pressable>
          )}

          {mode === 'in' ? (
            /* The margin lives on the Pressable, not on the Text inside it, so the touch
               target starts below the gap instead of at the button's edge. No hitSlop here
               for the same reason: this is the one control on the screen that must never be
               hit by accident. */
            <Pressable style={s.linkRow} onPress={forgot}>
              <Text style={[s.link, {textAlign: 'center'}]}>
                {asking ? t('forgotConfirm', {email: email.trim()}) : t('forgot')}
              </Text>
            </Pressable>
          ) : (
            <Text style={s.hint}>{t('signUpNote')}</Text>
          )}

          <Pressable style={s.linkRow} onPress={() => reset(mode === 'up' ? 'in' : 'up')}>
            <Text style={[s.link, {textAlign: 'center'}]}>
              {t(mode === 'up' ? 'signIn' : 'signUp')}
            </Text>
          </Pressable>
        </View>
      )}

      {error ? <Text style={s.error}>{error}</Text> : null}
      {note ? <Text style={s.done}>{note}</Text> : null}

      {/* The two documents, reachable before the account exists rather than only after.
          Apple asks for the privacy policy URL in App Store Connect, which is a different
          thing from a person being able to read it at the moment they are handing over an
          address. */}
      <View style={s.legalRow}>
        <Pressable onPress={() => Linking.openURL(`${LEGAL}/privacy/`)} hitSlop={8}>
          <Text style={s.legalLink}>{t('legalPrivacy')}</Text>
        </Pressable>
        <Pressable onPress={() => Linking.openURL(`${LEGAL}/terms/`)} hitSlop={8}>
          <Text style={s.legalLink}>{t('legalTerms')}</Text>
        </Pressable>
      </View>
    </View>
  );
}
